import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const read = async path => JSON.parse(await readFile(new URL(path, root), "utf8"));
const marketplace = await read(".agents/plugins/marketplace.json");
assert.equal(marketplace.name, "skillar");
const entry = marketplace.plugins.find(plugin => plugin.name === "skillar");
assert.equal(entry.source.path, "./plugins/skillar");
const manifest = await read("plugins/skillar/.codex-plugin/plugin.json");
assert.equal(manifest.name, "skillar");
const config = await read("plugins/skillar/.mcp.json");
assert.deepEqual(config.mcpServers.skillar, { type: "http", url: process.env.SKILLAR_MCP_URL ?? "https://skillar.example.invalid/mcp", scopes: ["skills:read", "skills:write"] });
const loader = await readFile(new URL("plugins/skillar/skills/skillar/SKILL.md", root), "utf8");
assert.ok(loader.includes("load_id") && loader.includes("expected_digest"));
console.log("Team plugin: direct HTTPS, no local command, no embedded credential; loader and marketplace present");
